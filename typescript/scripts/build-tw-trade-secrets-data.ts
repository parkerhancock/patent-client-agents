// Regenerates the bundled Taiwan Trade Secrets Act text from the official
// English translation on the Laws & Regulations Database (law.moj.gov.tw).
// One plain HTTP GET; no browser, cookies or challenge handling.
//
// Usage (from typescript/):
//   bun scripts/build-tw-trade-secrets-data.ts --fetch   # download, archive, regenerate
//   bun scripts/build-tw-trade-secrets-data.ts           # regenerate from the archived page
// Then run `bun run format` to apply Biome formatting to the generated module.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { gunzipSync, gzipSync } from "node:zlib";

export const SOURCE_URL =
  "https://law.moj.gov.tw/Eng/LawClass/LawAll.aspx?pcode=J0080028";
const root = join(import.meta.dir, "..");
/** The retrieved page, archived gzipped so formatters leave its bytes alone. */
const htmlPath = join(
  root,
  "tests/fixtures/tw-trade-secrets/J0080028-en.html.gz",
);
const sourcePath = join(root, "tests/fixtures/tw-trade-secrets/source.json");
const modulePath = join(root, "packages/client/src/tw-trade-secrets-data.ts");

const ENTITIES: Record<string, string> = {
  amp: "&",
  lt: "<",
  gt: ">",
  quot: '"',
  apos: "'",
  nbsp: " ",
};
function decode(value: string): string {
  return value.replace(
    /&(#x[\da-f]+|#\d+|[a-z]+);/gi,
    (match, name: string) => {
      if (name[0] === "#")
        return String.fromCodePoint(
          name[1] === "x" || name[1] === "X"
            ? Number.parseInt(name.slice(2), 16)
            : Number.parseInt(name.slice(1), 10),
        );
      return ENTITIES[name.toLowerCase()] ?? match;
    },
  );
}

export interface ParsedLaw {
  title: string;
  amended_date: string;
  source_last_updated: string | null;
  articles: { section: string; text: string }[];
}

/** Article rows of a LawAll.aspx page; `<br />` line breaks become newlines, text is otherwise verbatim. */
export function parseLawAll(html: string): ParsedLaw {
  const title = /<a id="hlLawName"[^>]*>([^<]+)</.exec(html)?.[1]?.trim();
  const amended = /Amended Date：\s*<\/th>\s*<td>\s*(\d{4}-\d{2}-\d{2})/.exec(
    html,
  )?.[1];
  const updated =
    /last update date of laws and regulations data：(\d{4})\/(\d{2})\/(\d{2})/.exec(
      html,
    );
  const articles = [
    ...html.matchAll(
      /<div class="col-no">Article ([0-9]+(?:-[0-9]+)?)<\/div><div class="col-data">([\s\S]*?)<\/div><\/div>/g,
    ),
  ].map((match) => ({
    section: match[1] as string,
    text: decode(
      (match[2] as string)
        .replace(/<br\s*\/?>/gi, "\n")
        .replace(/<[^>]+>/g, ""),
    )
      .split("\n")
      .map((line) => line.trim())
      .join("\n")
      .trim(),
  }));
  if (!title || !amended || articles.length === 0)
    throw new Error("The page does not have the expected LawAll layout.");
  const rows = (html.match(/<div class="col-no">/g) ?? []).length;
  if (rows !== articles.length)
    throw new Error(`Parsed ${articles.length} of ${rows} article rows.`);
  return {
    title,
    amended_date: amended,
    source_last_updated: updated
      ? `${updated[1]}-${updated[2]}-${updated[3]}`
      : null,
    articles,
  };
}

export const sha256 = (bytes: Uint8Array) =>
  createHash("sha256").update(bytes).digest("hex");

/** The generated TypeScript module for a parsed page and its retrieval record. */
export function renderModule(
  law: ParsedLaw,
  source: { retrieved_at: string; html_sha256: string },
): string {
  const meta = {
    source_url: SOURCE_URL,
    pcode: "J0080028",
    title: law.title,
    language: "en",
    amended_date: law.amended_date,
    source_last_updated: law.source_last_updated,
    retrieved_at: source.retrieved_at,
    html_sha256: source.html_sha256,
  };
  return `// Generated by scripts/build-tw-trade-secrets-data.ts from the official
// English translation (Laws & Regulations Database of the Republic of China).
// Do not edit by hand; regenerate and review the diff instead.

/** Where and when the bundled text was retrieved. */
export const TW_TRADE_SECRETS_SOURCE = ${JSON.stringify(meta, null, 2)} as const;

/** Every Article of the Act in statutory order, text as published. */
export const TW_TRADE_SECRETS_ARTICLES: readonly {
  readonly section: string;
  readonly text: string;
}[] = ${JSON.stringify(law.articles, null, 2)};
`;
}

if (import.meta.main) {
  if (process.argv.includes("--fetch")) {
    const response = await fetch(SOURCE_URL, {
      headers: { "user-agent": "patent-client-agents corpus refresh" },
    });
    if (!response.ok)
      throw new Error(`GET ${SOURCE_URL} returned ${response.status}.`);
    const bytes = new Uint8Array(await response.arrayBuffer());
    parseLawAll(new TextDecoder().decode(bytes));
    await writeFile(htmlPath, gzipSync(bytes, { level: 9 }));
    await writeFile(
      sourcePath,
      `${JSON.stringify(
        {
          source_url: SOURCE_URL,
          retrieved_at: new Date().toISOString().replace(/\.\d+Z$/, "Z"),
          html_sha256: sha256(bytes),
          bytes: bytes.byteLength,
        },
        null,
        2,
      )}\n`,
    );
  }
  const bytes = new Uint8Array(gunzipSync(await readFile(htmlPath)));
  const source = JSON.parse(await readFile(sourcePath, "utf8")) as {
    retrieved_at: string;
    html_sha256: string;
  };
  if (sha256(bytes) !== source.html_sha256)
    throw new Error("The archived page does not match source.json.");
  const law = parseLawAll(new TextDecoder().decode(bytes));
  await writeFile(modulePath, renderModule(law, source));
  console.log(
    `${law.articles.length} articles, amended ${law.amended_date}, written to ${modulePath}`,
  );
}
